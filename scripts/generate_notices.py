"""Regenerate ``NOTICES.txt`` from a CycloneDX SBOM.

Run from the repo root::

    python scripts/generate_notices.py [--sbom path/to/sbom.json] [--output NOTICES.txt] [--check]

The script consumes a CycloneDX 1.5 JSON SBOM produced by ``cyclonedx-npm`` /
``cyclonedx-py`` (merged) and emits a static-data + dependency attribution
file. It is the single source of truth for ``NOTICES.txt``: the file is
checked into the repo for auditability, and CI fails if the regenerated
output diverges from the committed copy.

Determinism rules — running this script twice on the same SBOM must produce
bit-identical bytes:

  * Components are sorted by ``(group, name, version)`` with case-folded keys
    so platform-specific filesystem ordering does not leak in.
  * The generator never reads the wall clock — no timestamps in the output.
  * Static asset blocks (GADM, OSM, climate-lama-engine, Inter) are emitted
    in a fixed order from the constants below.
  * The file ends with a single trailing ``\n`` and uses LF line endings on
    every platform.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Iterable
from pathlib import Path
from typing import TypedDict

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SBOM = REPO_ROOT / "sbom.json"
DEFAULT_OUTPUT = REPO_ROOT / "NOTICES.txt"

HEADER = """RISK WISE v2 — third-party attribution

This file is generated by `scripts/generate_notices.py` from the project
SBOM (`sbom.json`). Do not edit by hand: CI regenerates the file on every
release and fails if the committed copy differs from the generated output.

The static-asset section lists data sources and fonts that ship as bundled
artifacts and are therefore not present in the SBOM. The dependency section
lists every npm and pip package the build resolves, with its license
identifier and homepage URL.
"""


class StaticAsset(TypedDict):
    title: str
    license: str
    homepage: str
    notice: str


